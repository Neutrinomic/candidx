import { IDL } from '@icp-sdk/core/candid';
import { deepStrictEqual } from 'node:assert';
import { encodeCanonical } from '../dist/candid.js';
import { canonicalize } from '../dist/index.js';
const Old = IDL.Record({ a: IDL.Text });
const New = IDL.Record({ a: IDL.Text, b: IDL.Opt(IDL.Text) });
const Newer = IDL.Record({ a: IDL.Text, b: IDL.Opt(IDL.Text), c: IDL.Opt(IDL.Vec(IDL.Nat)) });
const NestedOption = IDL.Record({ a: IDL.Text, b: IDL.Opt(IDL.Opt(IDL.Text)) });
const Choice = IDL.Variant({ a: IDL.Null, b: IDL.Nat });
const MoreChoice = IDL.Variant({ a: IDL.Null, b: IDL.Nat, c: IDL.Text });
const OuterOld = IDL.Record({ inner: Old, items: IDL.Vec(Choice) });
const OuterNew = IDL.Record({ inner: New, items: IDL.Vec(MoreChoice), extra: IDL.Opt(IDL.Nat) });
function emit(name, type, value) {
  const raw = IDL.encode([type], [value]);
  const canonical = encodeCanonical([type], [value]);
  deepStrictEqual(canonical, canonicalize(raw), name);
  let expected = value;
  if (name === 'evolution-empty-byte-vector') expected = new Uint8Array();
  deepStrictEqual(IDL.decode([type], canonical), [expected], name);
  deepStrictEqual(canonicalize(canonical), canonical, name);
  console.log(`raw:${name} ${Buffer.from(raw).toString('hex')}`);
  console.log(`canonical:${name} ${Buffer.from(canonical).toString('hex')}`);
}
const old = a => ({ a });
const nw = (a, b = []) => ({ a, b });
const newer = (a, b = []) => ({ a, b, c: [] });
emit('evolution-record-old', Old, old('abc'));
emit('evolution-record-new', New, nw('abc'));
emit('evolution-record-newer', Newer, newer('abc'));
emit('evolution-present-empty', New, nw('abc', ['']));
emit('evolution-present-text', New, nw('abc', ['new data']));
emit('evolution-nested-none', NestedOption, { a: 'abc', b: [] });
emit('evolution-nested-some-none', NestedOption, { a: 'abc', b: [[]] });
emit('evolution-nested-some-some', NestedOption, { a: 'abc', b: [['x']] });
emit('evolution-variant-old', Choice, { b: 128n });
emit('evolution-variant-new', MoreChoice, { b: 128n });
emit('evolution-variant-used-new', MoreChoice, { c: 'new' });
emit('evolution-array-old', IDL.Vec(Old), [old('abc'), old('xyz')]);
emit('evolution-array-new', IDL.Vec(New), [nw('abc'), nw('xyz')]);
emit('evolution-array-mixed', IDL.Vec(New), [nw('abc'), nw('xyz', ['present'])]);
emit('evolution-array-mixed-newer', IDL.Vec(Newer), [newer('abc'), newer('xyz', ['present'])]);
emit('evolution-variant-array-old', IDL.Vec(Choice), [{ a: null }, { b: 5n }]);
emit('evolution-variant-array-new', IDL.Vec(MoreChoice), [{ a: null }, { b: 5n }]);
emit('evolution-outer-old', OuterOld, { inner: old('abc'), items: [{ b: 7n }] });
emit('evolution-outer-new', OuterNew, { inner: nw('abc'), items: [{ b: 7n }], extra: [] });
emit('evolution-empty-nat-vector', IDL.Vec(IDL.Nat), []);
emit('evolution-empty-text-vector', IDL.Vec(IDL.Text), []);
emit('evolution-empty-byte-vector', IDL.Vec(IDL.Nat8), new Uint8Array());
emit('evolution-option-none-nat', IDL.Opt(IDL.Nat), []);
emit('evolution-option-none-text', IDL.Opt(IDL.Text), []);
emit('evolution-option-some-none', IDL.Opt(IDL.Opt(IDL.Nat)), [[]]);
emit('evolution-option-some-some', IDL.Opt(IDL.Opt(IDL.Nat)), [[7n]]);
emit('evolution-nullable-array', IDL.Vec(IDL.Opt(IDL.Opt(IDL.Nat))), [[], [[]], [[7n]]]);
